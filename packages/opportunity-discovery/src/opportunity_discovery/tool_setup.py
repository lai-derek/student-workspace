"""Workspace setup and check hooks run by student-workspace."""

from __future__ import annotations

import json
import os
import subprocess
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from student_workspace.state import STATE_DIR, WorkspaceStateError, require_workspace

from . import db as dbm
from .config import collector_dir, load_workspace_config, registered_tool_path
from .registry import load_sources, sync_sources_to_db
from .review import _validated_board

TASK_NAME = "Student Workspace - Opportunity Discovery"
STALE_AFTER = timedelta(days=3)
RUN_HINT = r"`.\tools\.venv\Scripts\opdisc.exe --workspace . run` from the workspace folder"
DASHBOARD_MARKER = "rem Generated by opportunity-discovery setup."
DASHBOARD_CMD = (
    "@echo off\r\n"
    f"{DASHBOARD_MARKER}\r\n"
    "setlocal DisableDelayedExpansion\r\n"
    'set "WORKSPACE=%~dp0"\r\n'
    'set "WORKSPACE=%WORKSPACE:~0,-1%"\r\n'
    'set "OPDISC=%WORKSPACE%\\tools\\.venv\\Scripts\\opdisc.exe"\r\n'
    'if not exist "%OPDISC%" (\r\n'
    "  echo The dashboard is not installed. Run the Student Workspace setup again.\r\n"
    "  pause\r\n"
    "  exit /b 1\r\n"
    ")\r\n"
    "echo Opening dashboard. Close this window or press Ctrl+C to stop it.\r\n"
    '"%OPDISC%" dashboard "%WORKSPACE%"\r\n'
    'set "OPDISC_EXIT=%errorlevel%"\r\n'
    'if not "%OPDISC_EXIT%"=="0" pause\r\n'
    "exit /b %OPDISC_EXIT%\r\n"
)


def _write_dashboard_launcher(root: Path) -> str:
    path = root / "Open Dashboard.cmd"
    if path.exists():
        existing = path.read_bytes().decode("utf-8", errors="replace")
        if existing == DASHBOARD_CMD:
            return "unchanged"
        if DASHBOARD_MARKER not in existing:
            return "kept (not generated by setup)"
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(DASHBOARD_CMD)
    return "written"


def register_task(root: Path, *, script: Path | None = None) -> list[str]:
    """The Task Scheduler registration command for this workspace's daily collection."""
    if script is None:
        folder = registered_tool_path(root)
        if folder is None:
            raise WorkspaceStateError("register opportunity-discovery with student-workspace first")
        script = folder / "scripts" / "register-task.ps1"
    return [
        "powershell.exe",
        "-NoProfile",
        "-ExecutionPolicy",
        "Bypass",
        "-File",
        str(script),
        "-WorkspacePath",
        str(root),
        "-TaskName",
        TASK_NAME,
    ]


def setup_workspace(root: Path, *, schedule: bool = False) -> dict[str, Any]:
    """Create collector storage and the dashboard launcher; optionally schedule collection."""
    root, _metadata = require_workspace(root)
    (root / "opportunities").mkdir(exist_ok=True)
    state = collector_dir(root)
    for name in ("data", "output", "logs"):
        (state / name).mkdir(parents=True, exist_ok=True)
    cfg, errors = load_workspace_config(root)
    if errors:
        raise WorkspaceStateError("configuration errors: " + "; ".join(errors))
    conn = dbm.connect(cfg.paths.data_dir / "opdisc.sqlite3")
    try:
        dbm.migrate(conn)
        sources, _source_errors = load_sources(cfg.sources_file)
        sync_sources_to_db(conn, sources)
    finally:
        conn.close()
    result: dict[str, Any] = {
        "workspace": str(root),
        "collector_state": state.relative_to(root).as_posix(),
        "dashboard_launcher": _write_dashboard_launcher(root)
        if os.name == "nt"
        else "skipped (Windows only)",
        "scheduled_task": None,
    }
    if schedule:
        if os.name != "nt":
            raise WorkspaceStateError("daily scheduling is available on Windows only; use cron with run")
        completed = subprocess.run(register_task(root), capture_output=True, text=True, check=False)
        if completed.returncode != 0:
            raise WorkspaceStateError(
                "could not register the scheduled task: " + (completed.stdout + completed.stderr).strip()
            )
        result["scheduled_task"] = TASK_NAME
    return result


def check_workspace(root: Path, *, now: datetime | None = None) -> tuple[int, list[str]]:
    """0 current, 2 stale collection, 1 unreadable state."""
    root, _metadata = require_workspace(root)
    messages: list[str] = []
    try:
        board = root / STATE_DIR / "board.json"
        if board.exists():
            _validated_board(board)
        for name in ("screening-profile.json", "screening.json"):
            path = root / STATE_DIR / name
            if path.exists():
                json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, WorkspaceStateError) as exc:
        return 1, [f"opportunity state is unreadable: {exc}"]
    manifest_path = collector_dir(root) / "output" / "export_manifest.json"
    if not manifest_path.exists():
        return 0, [f"no collection yet; ask your AI to create your first board or run {RUN_HINT}"]
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        generated = datetime.fromisoformat(str(manifest["generated_at"]).replace("Z", "+00:00"))
    except (OSError, ValueError, KeyError) as exc:
        return 1, [f"collector export manifest is unreadable: {exc}"]
    age = (now or datetime.now(UTC)) - generated.astimezone(UTC)
    messages.append(f"last collection export {generated.isoformat()}")
    if age > STALE_AFTER:
        messages.append(
            f"collection is {age.days} days old; run {RUN_HINT} "
            "(if you turned on daily collection, check its log)"
        )
        return 2, messages
    return 0, messages
